-- Per-postal-code delivery minimums. Unmatched PLZ falls back to the global
-- `delivery_minimum` site setting. Delivery fee stays global.

begin;

create table if not exists public.delivery_zone_minimums (
  id bigint generated by default as identity primary key,
  postal_code text not null,
  minimum_order numeric(10, 2) not null check (minimum_order >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint delivery_zone_minimums_postal_code_unique unique (postal_code),
  constraint delivery_zone_minimums_postal_code_format
    check (postal_code ~ '^[0-9]{4}$')
);

create index if not exists delivery_zone_minimums_active_postal_idx
  on public.delivery_zone_minimums (is_active, postal_code);

alter table public.delivery_zone_minimums enable row level security;

create policy "Active delivery zone minimums are public"
  on public.delivery_zone_minimums for select
  to anon, authenticated
  using (is_active);

create policy "Admins manage delivery zone minimums"
  on public.delivery_zone_minimums for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

grant select on public.delivery_zone_minimums to anon, authenticated;
grant all on public.delivery_zone_minimums to authenticated;
grant usage, select on sequence public.delivery_zone_minimums_id_seq to authenticated;

commit;
